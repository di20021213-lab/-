"""Эвристика «похоже, нерабочая»: ищем признаки неисправности в заголовке и описании.

Главная сложность — отрицания. «Без артефактов», «не был в ремонте», «проблем нет» —
это признаки ХОРОШЕГО объявления, хотя слова-маркеры в них есть. Поэтому каждое
совпадение проверяем на отрицание рядом (в пределах предложения): до 3 слов перед
маркером и до 2 слов после.

Исключение — маркеры, которые сами начинаются с отрицания («не работает»,
«нерабочая», «не запускается»): для них отрицание и есть суть, их не перепроверяем.

ВАЖНО про «не греется»: для видеокарт это НЕ плюс, а тревожный признак — мёртвый
чип не греется, и продавец пишет «не греется» как достоинство, не упоминая, что карта
не работает. Поэтому «не греется» — отдельный маркер неисправности (см. список).
"""

from __future__ import annotations

import re
from typing import Iterable, Optional

# Признаки неисправности. Ищутся как подстроки (регистр не важен, ё = е).
BROKEN_MARKERS = (
    # прямые
    "не работает", "нерабоч", "не рабоч", "неисправ", "сломан",
    "на запчасти", "под восстановление", "донор", "труп", "мертв",
    # не запускается / не показывает
    "не запускается", "не включается", "не стартует", "не определяется",
    "не выводит", "не инициализ", "нет изображения", "нет картинки",
    "черный экран", "полосы на экране",
    # физические проблемы
    "отвал", "артефакт", "артефач", "перегрев", "греется", "дефект",
    "битая", "битый", "глюч", "троит",
    # «не греется» для видеокарты — тревожный признак: мёртвый чип не греется.
    # Начинается с «не», поэтому проверка отрицаний его не отменит — сработает всегда.
    "не греется",
    # ремонт
    "требует ремонта", "после ремонта", "был в ремонте", "ремонт",
    # неопределённость (часто = нерабочая)
    "не тестир", "не проверял", "не проверен", "непроверен", "как есть",
    # общие
    "проблем",
)

_NEGATION_EXACT = {"не", "без", "нет", "ноль", "никаких", "никакого", "никакой", "никакие"}
_NEGATION_PREFIX = ("отсутств", "исключ")

_SENTENCE_SPLIT = re.compile(r"[.!?;\n]")
_WORD = re.compile(r"[а-яa-z0-9]+")


def _self_negated(marker: str) -> bool:
    """Маркер сам начинается с отрицания — отрицание и есть смысл, не перепроверяем."""
    first = marker.split()[0]
    return first in ("не", "нет") or first.startswith(("нерабоч", "неисправ", "непровер"))


def _is_negation(word: str) -> bool:
    return word in _NEGATION_EXACT or word.startswith(_NEGATION_PREFIX)


def _negated_around(text: str, start: int, end: int) -> bool:
    """Есть ли отрицание рядом с совпадением — в том же предложении."""
    before = _SENTENCE_SPLIT.split(text[:start])[-1]
    if any(_is_negation(w) for w in _WORD.findall(before)[-3:]):
        return True
    after = _SENTENCE_SPLIT.split(text[end:])[0]
    return any(_is_negation(w) for w in _WORD.findall(after)[:2])


def broken_reason(*texts: Optional[str], extra: Iterable[str] = ()) -> Optional[str]:
    """Возвращает первый найденный признак неисправности (для лога/пометки) или None."""
    markers = tuple(BROKEN_MARKERS) + tuple(m.lower().replace("ё", "е") for m in extra)
    for raw in texts:
        if not raw:
            continue
        t = raw.lower().replace("ё", "е")
        for marker in markers:
            pos = 0
            while True:
                i = t.find(marker, pos)
                if i < 0:
                    break
                j = i + len(marker)
                if _self_negated(marker) or not _negated_around(t, i, j):
                    return marker
                pos = j
    return None
