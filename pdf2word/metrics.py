def _table(adv, lsb, rsb) -> dict[str, tuple[int, int, int]]:
    return {c: (a, l, r) for c, a, l, r in zip(_CHARS, adv, lsb, rsb)}


_GLYPHS = {
    False: _table(_REGULAR_ADV, _REGULAR_LSB, _REGULAR_RSB),
    True: _table(_BOLD_ADV, _BOLD_LSB, _BOLD_RSB),
}
_DEFAULT = (500, 30, 30)
SPACE = 0.25          # ширина пробела в долях кегля


def ink_width(text: str, bold: bool = False) -> float:
    """Ширина слова от первого до последнего штриха, в долях кегля."""
    if not text:
        return 0.0
    glyphs = _GLYPHS[bold]
    total = sum(glyphs.get(ch, _DEFAULT)[0] for ch in text)
    total -= glyphs.get(text[0], _DEFAULT)[1] + glyphs.get(text[-1], _DEFAULT)[2]
    return max(0.0, total / 1000.0)


def advance_width(text: str, bold: bool = False) -> float:
    """Место, которое слово занимает в строке, в долях кегля."""
    glyphs = _GLYPHS[bold]
    return sum(glyphs.get(ch, _DEFAULT)[0] for ch in text) / 1000.0
